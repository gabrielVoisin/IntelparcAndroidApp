def xml_text(value: str) -> str:
    return escape(value).replace("'", "\\'").replace('"', '\\"')


def write(folder: str, index: int) -> None:
    out = RES / folder / "strings.xml"
    out.parent.mkdir(parents=True, exist_ok=True)
    lines = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- Generated by tools/build_strings.py: edit the table there. -->", "<resources>"]
    for key, values in S.items():
        attr = ""
        lines.append(f'    <string name="{key}"{attr}>{xml_text(values[index])}</string>')
    lines.append("</resources>")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    import re

    for key, (fr, en) in S.items():
        if re.findall(r"%\d\$[sd]", fr) != re.findall(r"%\d\$[sd]", en):
            raise SystemExit(f"placeholders differ for {key}")
    write("values", 0)
    write("values-en", 1)
    print(f"{len(S)} strings written")
